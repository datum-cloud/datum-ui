/**
 * Render the token object as the committed `src/tokens.gen.ts`.
 * Output is deterministic so `check:tokens` can compare it byte-for-byte.
 */

const IDENT = /^[A-Z_$][\w$]*$/i

function key(k) {
  return IDENT.test(k) ? k : `'${k}'`
}

function literal(value, indent) {
  const pad = '  '.repeat(indent)
  const inner = '  '.repeat(indent + 1)
  if (typeof value === 'string')
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
  if (typeof value === 'number')
    return String(value)
  if (Array.isArray(value))
    return `[${value.map(v => literal(v, indent)).join(', ')}]`
  const entries = Object.entries(value)
  if (entries.length === 0)
    return '{}'
  return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${literal(v, indent + 1)},`).join('\n')}\n${pad}}`
}

export function serializeTokens(t) {
  const colorKeys = Object.keys(t.colors.light)
  const lines = []
  lines.push(
    '// AUTO-GENERATED by scripts/gen-tokens.mjs from the datum-ui CSS sheets — do not edit.',
    '// Regenerate: pnpm --filter @datum-cloud/datum-ui-tokens gen:tokens',
    '',
    '/** Raw Figma palette (figma-tokens.css). */',
    `export const palette = ${literal(t.palette, 0)} as const`,
    '',
    '/** Semantic colour roles, camelCased from the alpha.css custom properties. */',
    'export interface SemanticColors {',
    ...colorKeys.map(k => `  ${key(k)}: string`),
    '}',
    '',
    'export type ColorScheme = \'light\' | \'dark\'',
    '',
    '/** Semantic colours per scheme (alpha.css `:root` = light, `.dark` = dark). */',
    `export const colors: { light: SemanticColors, dark: SemanticColors } = ${literal(t.colors, 0)}`,
    '',
    '/** Spacing scale in px, keyed by Tailwind step (`spacing[4]` = `p-4` = 16). */',
    `export const spacing = ${literal(t.spacing, 0)} as const`,
    '',
    '/** Figma radius tokens in px. */',
    `export const radius = ${literal(t.radius, 0)} as const`,
    '',
    '/** The `rounded-*` scale as datum-ui renders it (derived from --radius), in px. */',
    `export const radiusScale = ${literal(t.radiusScale, 0)} as const`,
    '',
    '/**',
    ' * Type scale in px. `sizes` is the phone-width (< 48rem) scale — what the web',
    ' * renders on a phone; `sizesByBreakpoint` has all three steps.',
    ' */',
    `export const typography = ${literal(t.typography, 0)} as const`,
    '',
    '/** Font family names. Native resolves these per platform — see fontPostScriptNames. */',
    `export const fonts = ${literal(t.fonts, 0)} as const`,
    '',
    '/** Font file for each family name. */',
    `export const fontFiles = ${literal(t.fontFiles, 0)} as const`,
    '',
    '/** PostScript name embedded in each font file (the name iOS registers). */',
    `export const fontPostScriptNames = ${literal(t.fontPostScriptNames, 0)} as const`,
    '',
    '/** Motion tokens (motion.css). Easing as cubic-bezier tuples; durations in ms. */',
    `export const motion = ${literal(t.motion, 0)} as const`,
    '',
  )
  return lines.join('\n')
}
